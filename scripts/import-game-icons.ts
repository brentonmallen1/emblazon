/**
 * Turns vendored game-icons.net originals (assets/vendor/game-icons) into heraldic charge sources
 * in assets/heraldry/charges/, and regenerates assets/CREDITS.md. Run with `npm run import-icons`,
 * then `npm run assets` to compile. Works offline: it only reads the vendored copies.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { escapeXml } from '../src/core/svg.ts';
import { parsePath, pathBounds, serializePath, transformPath, type Command } from './lib/path.ts';

const VENDOR = 'assets/vendor/game-icons';
const OUT = 'assets/heraldry/charges';
const SAFE = 90;
/** Aspect ratio past which a charge counts as tall (or wide) rather than compact. */
const ELONGATED = 1.3;

interface Entry {
  id: string;
  source: string;
  name: string;
  plural: string;
  weight: number;
  tags: string[];
}
const manifest: { authors: Record<string, string>; icons: Entry[] } = JSON.parse(readFileSync(`${VENDOR}/manifest.json`, 'utf8'));

const credits = new Map<string, string[]>();

for (const icon of manifest.icons) {
  const [author, file] = icon.source.split('/');
  const authorName = manifest.authors[author];
  if (!authorName) throw new Error(`${icon.id}: no display name for author "${author}" in manifest.authors`);
  const svg = readFileSync(`${VENDOR}/${icon.source}.svg`, 'utf8');

  // Originals are a black background square plus white icon paths; keep only the icon.
  const paths: Command[][] = [...svg.matchAll(/<path ([^>]*?)\/?>/g)]
    .map((m) => m[1])
    .filter((attrs) => attrs.includes('fill="#fff"'))
    .map((attrs) => parsePath(attrs.match(/\bd="([^"]+)"/)![1]));
  if (paths.length === 0) throw new Error(`${icon.id}: no icon paths in ${icon.source}.svg`);

  const all = pathBounds(paths.flat());
  const w = all.maxX - all.minX;
  const h = all.maxY - all.minY;
  const s = SAFE / Math.max(w, h);
  const tx = 50 - ((all.minX + all.maxX) / 2) * s;
  const ty = 50 - ((all.minY + all.maxY) / 2) * s;

  const shape = h / w > ELONGATED ? 'tall' : w / h > ELONGATED ? 'wide' : 'compact';
  const tags = [shape, ...icon.tags];
  const credit = `${authorName}, game-icons.net, CC BY 3.0`;
  const body = paths.map((p) => `<path d="${serializePath(transformPath(p, s, tx, ty))}"/>`).join('\n');

  writeFileSync(
    `${OUT}/${icon.id}.svg`,
    `<!-- Adapted from game-icons.net "${file}" by ${authorName} (CC BY 3.0): background removed, rescaled, colour dropped.\n` +
      `     Generated by scripts/import-game-icons.ts from ${VENDOR}/${icon.source}.svg. Edit the importer or manifest, not this file. -->\n` +
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" data-id="${icon.id}" data-name="${escapeXml(icon.name)}" ` +
      `data-plural="${escapeXml(icon.plural)}" data-weight="${icon.weight}" data-tags="${tags.join(',')}" data-credit="${escapeXml(credit)}">\n${body}\n</svg>\n`,
  );
  credits.set(authorName, [...(credits.get(authorName) ?? []), `${file} → ${icon.name}`]);
  console.log(`imported ${icon.id.padEnd(12)} ${shape.padEnd(8)} ← ${icon.source}`);
}

const sections = [...credits.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([author, items]) => `### ${author}\n\n${items.map((i) => `- ${i}`).join('\n')}`)
  .join('\n\n');

writeFileSync(
  'assets/CREDITS.md',
  `# Credits

Original emblazon artwork (shields, lines of partition, ordinaries, furs and the hand-drawn and
geometric charges) is part of this project.

Some heraldic charges are adapted from [game-icons.net](https://game-icons.net), licensed under
[CC BY 3.0](https://creativecommons.org/licenses/by/3.0/). They were changed: background removed,
rescaled, colour dropped so the renderer can tint them. Unmodified originals are kept in
\`${VENDOR}/\`.

**Attribution line for anything that shows these emblems:**
Icons made by ${[...credits.keys()].sort().join(', ')} from game-icons.net, CC BY 3.0.

${sections}
`,
);
console.log(`wrote assets/CREDITS.md (${manifest.icons.length} icons, ${credits.size} authors)`);
