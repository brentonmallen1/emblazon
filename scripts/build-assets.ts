/**
 * Validates SVG charge sources against the asset contract (docs/PLAN.md §5) and compiles them
 * into src/themes/heraldry/charges.generated.ts, so the library needs no filesystem at runtime.
 * Run with `npm run assets`; exits non-zero and changes nothing if any asset is invalid.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

export const SRC_DIR = 'assets/heraldry/charges';
export const OUT_FILE = 'src/themes/heraldry/charges.generated.ts';

/** Shape elements and the only attributes they may carry. Colour, stroke and transforms belong to the renderer. */
const ALLOWED: Readonly<Record<string, readonly string[]>> = {
  path: ['d', 'fill-rule'],
  circle: ['cx', 'cy', 'r'],
  rect: ['x', 'y', 'width', 'height', 'rx', 'ry'],
  ellipse: ['cx', 'cy', 'rx', 'ry'],
  polygon: ['points', 'fill-rule'],
  g: ['fill-rule'],
};
const ROOT_ATTRS = ['xmlns', 'viewBox', 'data-id', 'data-name', 'data-plural', 'data-weight', 'data-tags'];

export interface CompiledAsset {
  id: string;
  name: string;
  plural: string;
  weight: number;
  tags: string[];
  markup: string;
}

const attrsOf = (text: string): Record<string, string> =>
  Object.fromEntries([...text.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

export function compileAsset(file: string, source: string): { asset?: CompiledAsset; errors: string[] } {
  const errors: string[] = [];
  const fail = (msg: string) => errors.push(`${file}: ${msg}`);

  const root = source.replace(/<!--[\s\S]*?-->/g, '').trim().match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/);
  if (!root) return { errors: [`${file}: must contain exactly one <svg> root element`] };

  const meta = attrsOf(root[1]);
  for (const key of Object.keys(meta)) if (!ROOT_ATTRS.includes(key)) fail(`unexpected root attribute "${key}"`);
  for (const key of ROOT_ATTRS) if (!(key in meta)) fail(`missing root attribute "${key}"`);
  if (meta.viewBox !== '0 0 100 100') fail(`viewBox must be "0 0 100 100", got "${meta.viewBox}"`);
  if (meta['data-id'] !== basename(file, '.svg')) fail(`data-id "${meta['data-id']}" must match the file name`);
  const weight = Number(meta['data-weight']);
  if (!(weight > 0)) fail(`data-weight must be a positive number`);

  const body = root[2];
  const tagRe = /<(\/?)([a-zA-Z][\w-]*)([^>]*?)\/?>/g;
  if (body.replace(tagRe, '').trim()) fail('stray text between elements');
  let shapes = 0;
  for (const [, closing, tag, attrText] of body.matchAll(tagRe)) {
    if (!(tag in ALLOWED)) {
      fail(`<${tag}> is not allowed`);
      continue;
    }
    if (closing) continue;
    if (tag !== 'g') shapes++;
    for (const [key, value] of Object.entries(attrsOf(attrText))) {
      if (!ALLOWED[tag].includes(key)) fail(`<${tag} ${key}> is not allowed; colour, stroke and transforms come from the renderer`);
      for (const [num] of value.matchAll(/-?\d*\.?\d+(?:e-?\d+)?/gi)) {
        const x = Number(num);
        if (!Number.isFinite(x) || x < -0.5 || x > 100.5) fail(`<${tag} ${key}> value ${num} lies outside the 100×100 viewBox`);
      }
    }
  }
  if (shapes === 0) fail('contains no shapes');

  if (errors.length) return { errors };
  return {
    errors,
    asset: {
      id: meta['data-id'],
      name: meta['data-name'],
      plural: meta['data-plural'],
      weight,
      tags: meta['data-tags'].split(',').map((t) => t.trim()).filter(Boolean),
      markup: body.replace(/>\s+</g, '><').trim(),
    },
  };
}

export function compileDir(dir: string = SRC_DIR): { assets: CompiledAsset[]; errors: string[] } {
  const assets: CompiledAsset[] = [];
  const errors: string[] = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
    const result = compileAsset(file, readFileSync(join(dir, file), 'utf8'));
    errors.push(...result.errors);
    if (result.asset) assets.push(result.asset);
  }
  return { assets, errors };
}

export function generateModule(assets: readonly CompiledAsset[]): string {
  const entries = assets.map(({ id, ...def }) => `  ${JSON.stringify(id)}: ${JSON.stringify(def)},`).join('\n');
  return (
    `// Generated by scripts/build-assets.ts from ${SRC_DIR}. Do not edit; run \`npm run assets\`.\n` +
    `import type { ChargeDef } from './charges.ts';\n\n` +
    `export const CHARGES = {\n${entries}\n} as const satisfies Readonly<Record<string, ChargeDef>>;\n`
  );
}

if (import.meta.main) {
  const { assets, errors } = compileDir();
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }
  writeFileSync(OUT_FILE, generateModule(assets));
  console.log(`compiled ${assets.length} charges → ${OUT_FILE}`);
}
