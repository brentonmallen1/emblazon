{
  // Outer circle minus a smaller circle shifted up; horns are where the circles cross.
  const r1 = 1;
  const r2 = 0.8;
  const d = 0.34;
  const a = (r1 * r1 - r2 * r2 + d * d) / (2 * d); // distance from outer centre to the chord
  const h = Math.sqrt(r1 * r1 - a * a);
  const { map, s } = fitBox(-r1, -a, r1, r1);
  const [lx, ly] = map([-h, -a]);
  const [rx, ry] = map([h, -a]);
  write(
    { id: 'crescent', name: 'crescent', plural: 'crescents', weight: 3, tags: ['compact', 'geometric'] },
    `<path d="M${n(lx)} ${n(ly)}A${n(r1 * s)} ${n(r1 * s)} 0 1 0 ${n(rx)} ${n(ry)}A${n(r2 * s)} ${n(r2 * s)} 0 1 1 ${n(lx)} ${n(ly)}Z"/>`,
  );
}

