/**
 * Authoring script for charges that are pure geometry. Writes SVG source files into
 * assets/heraldry/charges/; those files are the source of truth that build-assets.ts compiles.
 * Edit a shape here and re-run `npm run draw`, never the generated SVG.
 */
import { writeFileSync } from 'node:fs';
import { n } from '../src/core/svg.ts';

type P = [number, number];

const OUT = 'assets/heraldry/charges';
const SAFE = 90; // artwork fits a 90×90 box centred in the 100×100 viewBox

interface Meta {
  id: string;
  name: string;
  plural: string;
  weight: number;
  tags: string[];
}

function write(meta: Meta, body: string): void {
  const svg =
    `<!-- Generated by scripts/draw-geometric.ts. Edit the script, not this file. -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" data-id="${meta.id}" data-name="${meta.name}" ` +
    `data-plural="${meta.plural}" data-weight="${meta.weight}" data-tags="${meta.tags.join(',')}">\n${body}\n</svg>\n`;
  writeFileSync(`${OUT}/${meta.id}.svg`, svg);
  console.log(`drew ${meta.id}`);
}

// --- helpers ----------------------------------------------------------------------------------

const poly = (pts: readonly P[]): string => `M${pts.map(([x, y]) => `${n(x)} ${n(y)}`).join('L')}Z`;

/** Circle as a path, so it can share a fill-rule with other subpaths. */
const circle = (cx: number, cy: number, r: number): string =>
  `M${n(cx - r)} ${n(cy)}A${n(r)} ${n(r)} 0 1 0 ${n(cx + r)} ${n(cy)}A${n(r)} ${n(r)} 0 1 0 ${n(cx - r)} ${n(cy)}Z`;

/** Uniform scale + translate that centres a bounding box in the viewBox at SAFE size. */
function fitBox(minX: number, minY: number, maxX: number, maxY: number) {
  const s = SAFE / Math.max(maxX - minX, maxY - minY);
  const ox = 50 - ((minX + maxX) / 2) * s;
  const oy = 50 - ((minY + maxY) / 2) * s;
  return { s, map: ([x, y]: P): P => [ox + x * s, oy + y * s] };
}

function fit(pts: readonly P[]) {
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  return fitBox(Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys));
}

const polar = (r: number, a: number): P => [r * Math.cos(a), r * Math.sin(a)];

function star(points: number, inner: number): P[] {
  const pts: P[] = [];
  for (let i = 0; i < points * 2; i++) pts.push(polar(i % 2 ? inner : 1, -Math.PI / 2 + (i * Math.PI) / points));
  return pts;
}

/**
 * Star-shaped outline made of rays. Adjacent rays share their base points on a circle of
 * radius r0, so the hub is filled implicitly. `ray(k)` gives each ray's length and wave.
 */
function rays(count: number, r0: number, ray: (k: number) => { len: number; wave: number; cycles: number }): P[] {
  const half = Math.PI / count;
  const x0 = r0 * Math.cos(half);
  const hw = r0 * Math.sin(half);
  const pts: P[] = [];
  for (let k = 0; k < count; k++) {
    const { len, wave, cycles } = ray(k);
    const steps = wave ? 28 : 1; // straight rays need only their ends
    const theta = -Math.PI / 2 + (k * 2 * Math.PI) / count;
    const local = (t: number, side: -1 | 1): P => {
      const w = wave * Math.sin(2 * Math.PI * cycles * t) * Math.sqrt(1 - t);
      return [x0 + t * (len - x0), side * hw * (1 - t) + w];
    };
    const edge: P[] = [];
    for (let i = 0; i <= steps; i++) edge.push(local(i / steps, -1));
    for (let i = steps - 1; i >= 0; i--) edge.push(local(i / steps, 1));
    for (const [x, y] of edge) pts.push([x * Math.cos(theta) - y * Math.sin(theta), x * Math.sin(theta) + y * Math.cos(theta)]);
  }
  return pts;
}

