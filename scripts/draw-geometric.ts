{
  // Fan hinged at the top: scalloped rim along a circle, ribs cut out, ears on top.
  const [cx, cy, r] = [50, 45, 41];
  const a0 = Math.atan2(54 - cy, 10 - cx);
  const a1 = Math.atan2(54 - cy, 90 - cx);
  const lobes = 7;
  const rim: P[] = Array.from({ length: lobes + 1 }, (_, i) => {
    const a = a0 + ((a1 - a0) * i) / lobes;
    return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
  });
  const bump = n(Math.hypot(rim[1][0] - rim[0][0], rim[1][1] - rim[0][1]) * 0.6);
  let fan = `M50 21C30 21 12 33 ${n(rim[0][0])} ${n(rim[0][1])}`;
  for (const [x, y] of rim.slice(1)) fan += `A${bump} ${bump} 0 0 0 ${n(x)} ${n(y)}`;
  fan += `C88 33 70 21 50 21Z`;
  // Ribs: thin wedges from below the hinge out toward each notch between lobes.
  const ribs = rim.slice(1, -1).map(([x, y]) => {
    const len = Math.hypot(x - 50, y - 32);
    const [ux, uy] = [(x - 50) / len, (y - 32) / len];
    const end: P = [x - ux * 7, y - uy * 7];
    return poly([[50, 32], [end[0] - uy * 1.8, end[1] + ux * 1.8], [end[0] + uy * 1.8, end[1] - ux * 1.8]]);
  });
  write(
    { id: 'escallop', name: 'escallop', plural: 'escallops', weight: 2, tags: ['compact'] },
    `<path fill-rule="evenodd" d="${fan}${ribs.join('')}"/>\n<path d="M34 13H66L60 23H40Z"/>`,
  );
}
